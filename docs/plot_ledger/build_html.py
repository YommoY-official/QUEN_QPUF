import base64, io, re
from PIL import Image
def inline(m):
    p = OUT / m.group(1)
    im = Image.open(p).convert("RGB").quantize(64)
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return 'src="data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + '"'
